#!/bin/sh
# tools/theme-shots.sh <absolute scratch> <ofx binary> <out dir>: ofx under every Omarchy theme
# installed here (2026-11-07), one screenshot each, in the test weston (tools/gui/run-script.sh):
# never on Michael's screen, and never his theme (each theme is copied into the run's own theme
# folder, as the theme scripts do). The folder shows each colour ofx draws text in: the ls colours
# (folder, link, build file, README, executable, image, audio, archive, broken link), git's letters
# (modified, added, untracked, renamed, ignored), the columns, a marked row, the cursor, a hovered
# row, and the sidebar's drive with its bar. Nothing is written outside <scratch> and <out dir>.
set -eu
[ $# -eq 3 ] || { echo "usage: $0 <absolute scratch> <ofx binary> <out dir>" >&2; exit 2; }
T=$1 bin=$2 out=$3
case $T in /*) ;; *) echo "$0: the scratch dir must be absolute" >&2; exit 2 ;; esac
here=$(cd "$(dirname "$0")" && pwd)
rm -rf "$T"; mkdir -p "$T/tree/repo/src" "$T/fakes" "$T/themes" "$out"
# The test's git among the fakes (the guard runs no program outside the run's folder), as run.sh's.
printf '#!/bin/sh\nexec /usr/bin/git "$@"\n' > "$T/fakes/git"; chmod +x "$T/fakes/git"
( cd "$T/tree/repo"
  export GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL=/dev/null GIT_CEILING_DIRECTORIES="$T" GIT_AUTHOR_NAME=t GIT_AUTHOR_EMAIL=t@t GIT_COMMITTER_NAME=t GIT_COMMITTER_EMAIL=t@t
  git init -q -b main . && printf '*.log\n' > .gitignore && printf 'all:\n' > Makefile && printf '# r\n' > README.md && printf 'n\n' > notes.txt &&
  printf 'o\n' > old-name.txt && printf 'c\n' > changed.txt && printf '#!/bin/sh\n' > run.sh && chmod +x run.sh &&
  printf p > photo.png && printf s > song.mp3 && printf z > backup.zip && ln -s notes.txt link.txt && ln -s gone.txt broken-link &&
  mkdir docs && : > docs/d && git add -A && git commit -qm one &&
  git mv old-name.txt renamed.txt && printf 'c2\n' >> changed.txt && printf 's\n' > added.txt && git add added.txt &&
  printf 'u\n' > untracked.txt && printf 'l\n' > debug.log )
n=0
for f in /usr/share/omarchy/themes/*/colors.toml; do
    name=$(basename "$(dirname "$f")"); mkdir "$T/themes/$name"
    cp "$f" "$T/themes/$name/"; [ ! -f "$(dirname "$f")/icons.theme" ] || cp "$(dirname "$f")/icons.theme" "$T/themes/$name/"
done
{ echo "# generated by tools/theme-shots.sh"
  echo settle
  echo "wait-for 5000 gitshown=1"
  echo "key down"; echo "key down"; echo "press 5 ctrl"; echo "press 6 ctrl"
  echo "point-ui row 8"; echo "hover-here"
  for d in "$T"/themes/*/; do
      name=$(basename "$d")
      echo "sh C=\"\$OFX_ROOT/state/omarchy/current\"; rm -rf \"\$C/next\"; cp -r \"\$OFX_ROOT/themes/$name\" \"\$C/next\" && rm -rf \"\$C/theme\" && mv \"\$C/next\" \"\$C/theme\""
      echo "sleep 1200"
      echo "shot $name.png"
  done
  echo quit; } > "$T/themes.script"
OFX_TEST_HOME="$T/tree" "$here/gui/run-script.sh" "$T" "$T/themes.script" "$bin" "$T/tree/repo"
cp "$T"/shots/*.png "$out/"
rm -rf "$T"
